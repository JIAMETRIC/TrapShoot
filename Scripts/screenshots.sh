#!/bin/bash
# Screenshots of every screen in demo mode, light and dark, on an iPhone and an iPad simulator.
# Usage: Scripts/screenshots.sh <path to TrapShooterPro.app built for the simulator> <output folder>
# Runs in CI (.github/workflows/screenshots.yml) and on any Mac with Xcode.
set -euo pipefail
APP="$1"; OUT="$2"
BUNDLE=com.mtajudeen.trapshooterpro
SECTIONS="record timer rounds analysis schemes settings"
mkdir -p "$OUT"

udid() {  # first available simulator whose name matches $1, else the first matching $2
  xcrun simctl list devices available | grep -m1 -E "$1" | grep -oE '[0-9A-F-]{36}' || \
  xcrun simctl list devices available | grep -m1 -E "$2" | grep -oE '[0-9A-F-]{36}'
}

shoot() {  # device-udid label
  local dev="$1" label="$2"
  xcrun simctl boot "$dev" 2>/dev/null || true
  xcrun simctl bootstatus "$dev" -b >/dev/null
  xcrun simctl status_bar "$dev" override --time "9:41" --batteryState charged --batteryLevel 100 --cellularBars 4 --wifiBars 3 || true
  xcrun simctl install "$dev" "$APP"
  for look in light dark; do
    xcrun simctl ui "$dev" appearance "$look"
    for s in $SECTIONS; do
      xcrun simctl terminate "$dev" "$BUNDLE" 2>/dev/null || true
      xcrun simctl launch "$dev" "$BUNDLE" -demo -state.section "$s" >/dev/null
      sleep 6
      xcrun simctl io "$dev" screenshot --type=png "$OUT/$label-$look-$s.png" >/dev/null
      echo "$label $look $s"
    done
  done
  xcrun simctl shutdown "$dev" || true
}

shoot "$(udid 'iPhone 16 Pro \(' 'iPhone')" iphone
shoot "$(udid 'iPad Pro 13-inch' 'iPad')" ipad

# a page that shows them all on GitHub
{
  echo "# TrapShoot screenshots"
  echo
  echo "Demo mode, generated by CI from \`${GITHUB_SHA:-local}\`."
  for label in iphone ipad; do
    for look in light dark; do
      echo; echo "## $label, $look"; echo
      for s in $SECTIONS; do echo "<img src=\"$label-$look-$s.png\" width=\"$([ $label = iphone ] && echo 260 || echo 420)\" alt=\"$s\">"; done
    done
  done
} > "$OUT/README.md"
